const DICTS: Record<UILang, Dict> = { ru, kk }

export const USER_ROLES: UserRole[] = [
  'school_teacher',
  'college_teacher',
  'university_teacher',
  'student',
  'other',
]
const ROLE_KEYS = new Set<string>(USER_ROLES)

type Vars = Record<string, string | number>

interface I18nValue {
  lang: UILang
  setLang: (l: UILang) => void
  t: (key: string, vars?: Vars) => string
  tType: (v: MaterialType) => string
  tDiff: (v: Difficulty) => string
  tInst: (v: EducationLevel) => string
  tLang: (v: Lang) => string
  tSubject: (v: string) => string
  tGrade: (v: string) => string
  tTitle: (m: Pick<Material, 'title' | 'titleKk'>) => string
  tSummary: (m: Pick<Material, 'summary' | 'summaryKk'>) => string
  /** Переводит канонический ключ роли (UserRole); незнакомую строку возвращает как есть. */
  tRole: (v: string) => string
}

const I18nContext = createContext<I18nValue | null>(null)

function getInitial(): UILang {
  try {
    const s = localStorage.getItem(KEY)
    if (s === 'ru' || s === 'kk') return s
  } catch {
    /* ignore */
  }
  return 'ru'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UILang>(getInitial)

  const setLang = useCallback((l: UILang) => {
    setLangState(l)
    try {
      localStorage.setItem(KEY, l)
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l
  }, [])

  const t = useCallback(
    (key: string, vars?: Vars) => {
      let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t,
      tType: (v) => t(`type.${v}`),
      tDiff: (v) => t(`diff.${v}`),
      tInst: (v) => t(`inst.${v}`),
      tLang: (v) => t(`lang.${v}`),
      tSubject: (v) => t(`subject.${v}`),
      tGrade: (v) => (lang === 'kk' ? v.replace(/класс/g, 'сынып') : v),
      tTitle: (m) => (lang === 'kk' && m.titleKk ? m.titleKk : m.title),
      tSummary: (m) => (lang === 'kk' && m.summaryKk ? m.summaryKk : m.summary),
      tRole: (v) => (ROLE_KEYS.has(v) ? t(`role.${v}`) : v),
    }),
    [lang, setLang, t],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>')
  return ctx
}
